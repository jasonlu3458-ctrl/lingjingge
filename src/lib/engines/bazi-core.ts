/** 天干 → 五行（甲乙木、丙丁火、戊己土、庚辛金、壬癸水） */
export const STEM_TO_ELEMENT: Record<string, '木' | '火' | '土' | '金' | '水'> = {
  甲: '木', 乙: '木',
  丙: '火', 丁: '火',
  戊: '土', 己: '土',
  庚: '金', 辛: '金',
  壬: '水', 癸: '水',
};

/** 地支 → 五行（按五行三合局划分） */
export const BRANCH_TO_ELEMENT: Record<string, '木' | '火' | '土' | '金' | '水'> = {
  子: '水', 亥: '水',         // 亥子北方水
  寅: '木', 卯: '木',         // 寅卯东方木
  巳: '火', 午: '火',         // 巳午南方火
  申: '金', 酉: '金',         // 申酉西方金
  辰: '土', 戌: '土', 丑: '土', 未: '土',  // 四季末土
};

/** 五行 → 代表色（供人格解读 / 五行建议共用） */
export const ELEMENT_COLOR: Record<string, string> = {
  木: '青、绿',
  火: '红、紫',
  土: '黄、咖',
  金: '白、银、金',
  水: '黑、蓝',
};

/**
 * 工具函数：取天干对应五行，未知天干返回 '木'（保底）
 * 设计为不抛异常，确保所有调用方都能安全降级。
 */
export function elementOfStem(stem: string): '木' | '火' | '土' | '金' | '水' {
  return STEM_TO_ELEMENT[stem] ?? '木';
}

/**
 * 工具函数：取地支对应五行，未知地支返回 '土'（保底）
 */
export function elementOfBranch(branch: string): '木' | '火' | '土' | '金' | '水' {
  return BRANCH_TO_ELEMENT[branch] ?? '土';
}
